# ── MathView — міні-гра «математична задача» ──────────────────────────────────

class MathView(discord.ui.View):
    """
    Показує просту арифметичну задачу з 3 кнопками-варіантами.
    callback(won: bool) викликається після вибору або timeout.
    """
    def __init__(self, owner_id: int, callback):
        super().__init__(timeout=15)
        self.owner_id    = owner_id
        self._callback   = callback
        self._answered   = False

        a = random.randint(5, 30)
        b = random.randint(2, 20)
        op = random.choice(["+", "-", "×"])
        if op == "+":   correct = a + b
        elif op == "-": correct = a - b
        else:           correct = a * b
        self.question = f"{a} {op} {b} = ?"
        self.correct  = correct

        wrongs = set()
        while len(wrongs) < 2:
            delta = random.randint(1, max(3, abs(correct) // 5 + 1))
            w = correct + random.choice([-1, 1]) * delta
            if w != correct:
                wrongs.add(w)
        options = [correct] + list(wrongs)
        random.shuffle(options)

        for opt in options:
            btn = discord.ui.Button(
                label=str(opt),
                style=discord.ButtonStyle.primary
            )
            async def _handler(interaction: discord.Interaction, answer=opt):
                if interaction.user.id != self.owner_id:
                    return await interaction.response.send_message("❌ Не твоя гра!", ephemeral=True)
                if self._answered:
                    return
                self._answered = True
                for child in self.children:
                    child.disabled = True
                won = (answer == self.correct)
                await interaction.response.edit_message(view=self)
                await self._callback(won)
            btn.callback = _handler
            self.add_item(btn)

    async def on_timeout(self):
        if not self._answered:
            self._answered = True
            for child in self.children:
                child.disabled = True
            await self._callback(False)  

    async def interaction_check(self, interaction: discord.Interaction) -> bool:
        return interaction.user.id == self.owner_id

