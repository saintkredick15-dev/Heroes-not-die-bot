class ImageGenerator:
    def __init__(
        self,
        width: int = 2000,
        height: int = 750,
        bg_top_color: tuple = (7, 10, 28),
        bg_bottom_color: tuple = (27, 28, 62),
    ):
        self.width = width
        self.height = height
        self.bg_top_color = bg_top_color
        self.bg_bottom_color = bg_bottom_color

    def _draw_gradient(self, img):
        draw = ImageDraw.Draw(img)

        for y in range(self.height):
            ratio = y / self.height

            r = int(
                self.bg_top_color[0] * (1 - ratio) + self.bg_bottom_color[0] * ratio
            )
            g = int(
                self.bg_top_color[1] * (1 - ratio) + self.bg_bottom_color[1] * ratio
            )
            b = int(
                self.bg_top_color[2] * (1 - ratio) + self.bg_bottom_color[2] * ratio
            )

            draw.line([(0, y), (self.width, y)], fill=(r, g, b))

    def _center_text(self, draw, text, font):
        bbox = draw.textbbox((0, 0), text, font=font)
        text_width = bbox[2] - bbox[0]
        text_height = bbox[3] - bbox[1]

        x = (self.width - text_width) / 2
        y = (self.height - text_height) / 2 - bbox[1]

        return x, y

class Divider(ImageGenerator):
    def __init__(
        self,
        width: int = 2000,
        height: int = 35,
        gradient_top_color: tuple = (17, 18, 42),
        gradient_bottom_color: tuple = (27, 28, 62),
    ):
        self.gradient_top_color = gradient_top_color
        self.gradient_bottom_color = gradient_bottom_color

        super().__init__(width, height, gradient_top_color, gradient_bottom_color)

    def render_to_bytes(self, fmt="PNG"):
        img = Image.new("RGB", (self.width, self.height))
        self._draw_gradient(img)

        buffer = BytesIO()
        img.save(buffer, format=fmt)
        buffer.seek(0)

        return buffer

class Badge(ImageGenerator):
    def __init__(
        self,
        background_image_path: str = "images/badge_bg.png",  
        title_font_filename: str = "ScienceGothic.ttf",
    ):
        assets_path = "../assets"

        self.background_image = Image.open(
            f"{assets_path}/{background_image_path}"
        ).convert("RGB")
        width, height = self.background_image.size

        super().__init__(width, height)

        self.title_color = (164, 182, 186)

        base_font_path = f"{assets_path}/fonts/"
        self.title_font_path = f"{base_font_path}{title_font_filename}"

    def _load_font(self, size: int, font_path: str = None):
        if font_path:
            return ImageFont.truetype(font_path, size)
        return ImageFont.load_default()

    def _generate_image(self, title_text):
        img = self.background_image.copy()

        draw = ImageDraw.Draw(img)

        title_font = self._load_font(130, self.title_font_path)

        title_x, title_y = self._center_text(draw, title_text, title_font)

        draw.text(
            (title_x, title_y), title_text, fill=self.title_color, font=title_font
        )

        return img

    def render_to_bytes(self, title_text, fmt="PNG"):
        img = self._generate_image(title_text)

        buffer = BytesIO()
        img.save(buffer, format=fmt)
        buffer.seek(0)

        return buffer

